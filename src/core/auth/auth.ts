import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { nextCookies } from "better-auth/next-js";

import { deleteStripeCustomer } from "@/core/billing/customer";
import { db } from "@/core/db";
import * as schema from "@/core/db/schema";
import { sendEmail } from "@/core/email/send";
import { DeleteAccountEmail, ResetPasswordEmail, VerifyEmail } from "@/core/email/templates";
import { env } from "@/core/env";

// SKIP_EMAIL_VERIFICATION=true in .env: no confirmation emails, and new
// accounts are logged in straight after signing up. For demos only (see env.ts).
const verifyEmails = !env.SKIP_EMAIL_VERIFICATION;

if (!verifyEmails) {
  console.warn("Email verification is OFF (SKIP_EMAIL_VERIFICATION=true). Don't use this in production.");
}

// The whole auth setup in one place. Users, sessions and OAuth accounts live in
// our own Postgres, in tables generated by the Better Auth CLI (core/db/auth-schema.ts).
export const auth = betterAuth({
  baseURL: env.BETTER_AUTH_URL,
  secret: env.BETTER_AUTH_SECRET,
  database: drizzleAdapter(db, { provider: "pg", schema }),

  emailAndPassword: {
    enabled: true,
    requireEmailVerification: verifyEmails,
    // A reset usually means the password leaked: log out every other device too.
    revokeSessionsOnPasswordReset: true,
    sendResetPassword: async ({ user, url }) => {
      await sendEmail({
        to: user.email,
        subject: "Reset your ShipLink password",
        react: ResetPasswordEmail({ url }),
      });
    },
  },

  emailVerification: {
    sendOnSignUp: verifyEmails,
    // Lost the first email? Trying to log in sends a fresh one.
    sendOnSignIn: verifyEmails,
    autoSignInAfterVerification: true,
    sendVerificationEmail: async ({ user, url }) => {
      await sendEmail({
        to: user.email,
        subject: "Confirm your email for ShipLink",
        react: VerifyEmail({ url }),
      });
    },
  },

  // Google sign-in is switched on only when both keys are set (see env.ts).
  socialProviders:
    env.GOOGLE_CLIENT_ID && env.GOOGLE_CLIENT_SECRET
      ? { google: { clientId: env.GOOGLE_CLIENT_ID, clientSecret: env.GOOGLE_CLIENT_SECRET } }
      : {},

  user: {
    deleteUser: {
      enabled: true,
      // DECISION: deleting an account is confirmed with an email link. It works
      // the same for password and Google users, so we never ask for a password.
      sendDeleteAccountVerification: async ({ user, url }) => {
        await sendEmail({
          to: user.email,
          subject: "Confirm deleting your ShipLink account",
          react: DeleteAccountEmail({ url }),
        });
      },
      // Stop billing before the user row (and our copy of their subscription) is gone.
      beforeDelete: async (user) => {
        await deleteStripeCustomer(user.id);
      },
    },
  },

  // Lets server actions set auth cookies. Must stay the last plugin.
  plugins: [nextCookies()],
});
